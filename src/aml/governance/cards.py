"""Model cards: one Markdown page per model, generated from what the model stored.

A card holds no hand-typed number. `collect_facts` asks one adapter per model
(`aml.governance.sources`) for the facts of the stored model; `render_card` turns them into text
with no timestamp, LF line ends and one final newline, so the same facts always give the same
bytes and `--check` can tell a card that went stale. Writing a card is audited, but a card that is
already up to date is neither rewritten nor audited again.
"""

from __future__ import annotations

import hashlib
import importlib
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from aml.common.audit import audit
from aml.common.config import MODEL_CARD_NAMES, Settings
from aml.common.db import Database

__all__ = [
    "CARD_SOURCES",
    "MODEL_CARDS",
    "NEVER_ACTS",
    "AuditCoverage",
    "CardFacts",
    "CardReport",
    "Skipped",
    "collect_facts",
    "render_card",
    "write_cards",
]

MODEL_CARDS = (
    MODEL_CARD_NAMES  # ("prioritization", "memo_classifier", "anomaly", "screening_match")
)
CARD_SOURCES: dict[str, str] = {  # card name -> "module:function" returning CardFacts | Skipped
    "prioritization": "aml.governance.sources:prioritization_facts",
    "memo_classifier": "aml.governance.sources:memo_classifier_facts",
    "anomaly": "aml.governance.sources:anomaly_facts",
    "screening_match": "aml.governance.sources:screening_match_facts",
}
NEVER_ACTS = "This model never closes, clears, files or dispositions anything."
MODULE = "governance"


@dataclass(frozen=True)
class AuditCoverage:
    module: str
    decision: str
    rows: int  # audit rows of that decision
    with_version: int  # rows that carry the version of the card
    version: str | None = None  # the version those rows should carry, when it is not the card's


@dataclass(frozen=True)
class CardFacts:
    name: str  # one of MODEL_CARDS
    title: str
    version: str
    kind: str
    trained: str | None  # ISO UTC
    seed: int | None
    data_hash: str | None
    feature_version: str | None
    features: tuple[str, ...]
    source: str  # e.g. "case_models.model_id=1"
    intended_use: str
    oversight: str  # the sentence that is specific to this model, after NEVER_ACTS
    data: tuple[str, ...]  # bullets
    metrics: tuple[tuple[str, str, str], ...]  # (population, metric, formatted value)
    limitations: tuple[str, ...]
    audit: tuple[AuditCoverage, ...]


@dataclass(frozen=True)
class Skipped:
    name: str
    reason: str


@dataclass(frozen=True)
class CardReport:
    written: tuple[str, ...]  # paths of the cards written
    skipped: tuple[Skipped, ...]
    stale: tuple[str, ...]  # check mode only: cards that are missing or differ from the facts


def _cell(value: object) -> str:
    return "-" if value is None else str(value).replace("|", r"\|").replace("\n", " ")


def render_card(facts: CardFacts) -> str:
    """The Markdown text of a card. Pure and deterministic."""
    f = facts
    feature_set = (
        "-" if f.feature_version is None else f"{f.feature_version} ({len(f.features)} features)"
    )
    lines = [
        f"# Model card: {f.title}",
        "",
        f"> Generated by `aml models card` from {f.source}. "
        "Do not edit by hand: rerun the command.",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Model | {_cell(f.name)} |",
        f"| Version | {_cell(f.version)} |",
        f"| Kind | {_cell(f.kind)} |",
        f"| Trained | {_cell(f.trained)} |",
        f"| Seed | {_cell(f.seed)} |",
        f"| Data hash | {_cell(f.data_hash)} |",
        f"| Feature set | {_cell(feature_set)} |",
        "",
        "## Intended use",
        f.intended_use,
        "",
        "## Human oversight",
        NEVER_ACTS,
        f.oversight,
        "",
        "## Data",
        *[f"- {line}" for line in f.data],
        "",
        "## Features",
        ", ".join(f.features) if f.features else "-",
        "",
        "## Metrics",
        "| Population | Metric | Value |",
        "|---|---|---|",
        *[f"| {_cell(p)} | {_cell(m)} | {_cell(v)} |" for p, m, v in f.metrics],
        "",
        "## Limitations",
        *[f"- {line}" for line in f.limitations],
        "",
        "## Audit trail",
        *[
            f"- {a.module}/{a.decision}: {a.with_version} of {a.rows} row(s) carry version "
            f"{a.version or f.version}"
            for a in f.audit
        ],
    ]
    return "\n".join(lines) + "\n"


_NOT_IMPLEMENTED = {  # module probed by an adapter -> the spec that builds it
    "aml.ml.anomaly.card": "ml-anomaly",
    "aml.screening.ml.pipeline": "screening-ml",
}


def not_implemented(module: str) -> str:
    """The reason given when the module of a sibling spec cannot be imported."""
    return f"{module} is not implemented yet (specs/{_NOT_IMPLEMENTED[module]}.md)"


def collect_facts(
    db: Database, settings: Settings, names: Sequence[str]
) -> list[CardFacts | Skipped]:
    """The facts of each named model, or why there are none (reads only)."""
    out: list[CardFacts | Skipped] = []
    for name in names:
        module, function = CARD_SOURCES[name].split(":")
        out.append(getattr(importlib.import_module(module), function)(db, settings))
    return out


def write_cards(
    db: Database,
    settings: Settings,
    *,
    out_dir: Path | None = None,
    names: Sequence[str] | None = None,
    check: bool = False,
    actor: str | None = None,
) -> CardReport:
    """Write the card of each model (``ml.governance.models`` by default) where its text changed.

    With ``check`` nothing is written or audited: the report lists the cards that are missing or
    differ from what would be generated.
    """
    cfg = settings.ml.governance
    target = Path(out_dir) if out_dir is not None else settings.path(cfg.cards_dir)
    actor = actor or settings.audit.system_actor
    written: list[str] = []
    skipped: list[Skipped] = []
    stale: list[str] = []
    for facts in collect_facts(db, settings, list(names) if names is not None else cfg.models):
        if isinstance(facts, Skipped):
            skipped.append(facts)
            continue
        path = target / f"{facts.name}.md"
        data = render_card(facts).encode("utf-8")
        if path.exists() and path.read_bytes() == data:
            continue
        if check:
            stale.append(str(path))
            continue
        audit(  # audited first: a card on disk always has its audit row
            db,
            module=MODULE,
            entity_type="model_card",
            entity_id=facts.name,
            decision="MODEL_CARD_WRITTEN",
            reason=f"wrote the model card of {facts.version} to {path} from {facts.source}",
            version=facts.version,
            actor=actor,
            details={
                "path": str(path),
                "sha256": hashlib.sha256(data).hexdigest(),
                "source": facts.source,
            },
        )
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        written.append(str(path))
    return CardReport(tuple(written), tuple(skipped), tuple(stale))
